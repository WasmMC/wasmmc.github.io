#!/usr/bin/env python3
"""Verify LLVM target families and their reviewed bundle disposition."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import sys


def parse_cmake_set(text: str, name: str) -> set[str]:
    match = re.search(rf"set\s*\(\s*{re.escape(name)}\b(.*?)\)", text, re.DOTALL)
    if not match:
        raise ValueError(f"could not find {name} in LLVM CMakeLists.txt")
    body = re.sub(r"#[^\n]*", "", match.group(1))
    tokens = re.findall(r"[A-Za-z][A-Za-z0-9_]*", body)
    if not tokens:
        raise ValueError(f"{name} is empty in LLVM CMakeLists.txt")
    return set(tokens)


def parse_target_sets(path: Path) -> tuple[set[str], set[str]]:
    text = path.read_text(encoding="utf-8")
    stable = parse_cmake_set(text, "LLVM_ALL_TARGETS")
    experimental = parse_cmake_set(text, "LLVM_ALL_EXPERIMENTAL_TARGETS")
    overlap = stable & experimental
    if overlap:
        raise ValueError(f"upstream target sets overlap: {sorted(overlap)}")
    return stable, experimental


def analyze(inventory: dict, llvm_version: str, stable: set[str],
            experimental: set[str]) -> dict:
    expected_stable = set(inventory.get("stable", []))
    expected_experimental = set(inventory.get("experimental", []))
    expected_all = expected_stable | expected_experimental
    actual_all = stable | experimental
    bundles = inventory.get("bundles", {})
    excluded = set(inventory.get("excluded", {}))
    bundled_list = [target for targets in bundles.values() for target in targets]
    bundled = set(bundled_list)

    inventory_errors = []
    if inventory.get("schema") != 1:
        inventory_errors.append("inventory schema must be 1")
    overlap = expected_stable & expected_experimental
    if overlap:
        inventory_errors.append(f"stable/experimental overlap: {sorted(overlap)}")
    duplicates = sorted({target for target in bundled_list if bundled_list.count(target) > 1})
    if duplicates:
        inventory_errors.append(f"targets assigned to multiple bundles: {duplicates}")
    if bundled & excluded:
        inventory_errors.append(f"bundled and excluded overlap: {sorted(bundled & excluded)}")
    if bundled | excluded != expected_all:
        inventory_errors.append(
            "bundle/exclusion disposition does not cover reviewed targets: "
            f"missing={sorted(expected_all - bundled - excluded)} "
            f"unknown={sorted((bundled | excluded) - expected_all)}"
        )

    changes = {
        "version_mismatch": (
            None if inventory.get("llvm_version") == llvm_version else {
                "reviewed": inventory.get("llvm_version"), "actual": llvm_version,
            }
        ),
        "added_stable": sorted(stable - expected_all),
        "added_experimental": sorted(experimental - expected_all),
        "removed": sorted(expected_all - actual_all),
        "promoted_to_stable": sorted(stable & expected_experimental),
        "demoted_to_experimental": sorted(experimental & expected_stable),
    }
    changed = any(value for value in changes.values())
    return {
        "schema": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "llvm_version": llvm_version,
        "reviewed_version": inventory.get("llvm_version"),
        "ok": not inventory_errors and not changed,
        "inventory_errors": inventory_errors,
        "actual": {
            "stable": sorted(stable),
            "experimental": sorted(experimental),
        },
        "reviewed": {
            "stable": sorted(expected_stable),
            "experimental": sorted(expected_experimental),
            "bundles": bundles,
            "excluded": inventory.get("excluded", {}),
        },
        "changes": changes,
    }


def print_summary(report: dict) -> None:
    if report["ok"]:
        print(
            f"LLVM {report['llvm_version']} target inventory matches: "
            f"{len(report['actual']['stable'])} stable, "
            f"{len(report['actual']['experimental'])} experimental"
        )
        return
    print("LLVM target inventory requires review:", file=sys.stderr)
    for error in report["inventory_errors"]:
        print(f"  inventory: {error}", file=sys.stderr)
    for name, value in report["changes"].items():
        if value:
            print(f"  {name}: {value}", file=sys.stderr)


def write_cmake_cache(path: Path, report: dict) -> None:
    bundled = {
        target for targets in report["reviewed"]["bundles"].values() for target in targets
    }
    stable = sorted(bundled & set(report["actual"]["stable"]))
    experimental = sorted(bundled & set(report["actual"]["experimental"]))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by check_llvm_targets.py; do not edit.\n"
        f"set(LLVM_TARGETS_TO_BUILD \"{';'.join(stable)}\" CACHE STRING \"\" FORCE)\n"
        f"set(LLVM_EXPERIMENTAL_TARGETS_TO_BUILD \"{';'.join(experimental)}\" "
        "CACHE STRING \"\" FORCE)\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--llvm-cmake", type=Path, required=True)
    parser.add_argument("--llvm-version", required=True)
    parser.add_argument(
        "--inventory", type=Path,
        default=Path(__file__).resolve().parents[1] / "regression/llvm-target-inventory.json",
    )
    parser.add_argument("--report", type=Path)
    parser.add_argument("--cmake-cache", type=Path)
    args = parser.parse_args()

    try:
        inventory = json.loads(args.inventory.read_text(encoding="utf-8"))
        stable, experimental = parse_target_sets(args.llvm_cmake)
        report = analyze(inventory, args.llvm_version, stable, experimental)
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(
                json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
            )
        if args.cmake_cache:
            write_cmake_cache(args.cmake_cache, report)
        print_summary(report)
        if report["inventory_errors"]:
            return 2
        return 0 if report["ok"] else 1
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
